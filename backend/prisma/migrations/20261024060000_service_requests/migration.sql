CREATE TABLE `service_requests` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `tenant_id` INTEGER NOT NULL,
  `customer_id` INTEGER NOT NULL,
  `requester_id` INTEGER NOT NULL,
  `order_id` INTEGER NULL,
  `processor_id` INTEGER NULL,
  `request_no` VARCHAR(40) NOT NULL,
  `client_key` VARCHAR(64) NOT NULL,
  `type` VARCHAR(32) NOT NULL,
  `subject` VARCHAR(120) NOT NULL,
  `description` TEXT NOT NULL,
  `status` VARCHAR(32) NOT NULL DEFAULT 'pending',
  `version` INTEGER NOT NULL DEFAULT 0,
  `resolution` TEXT NULL,
  `events` JSON NOT NULL DEFAULT ('[]'),
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  `closed_at` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `service_requests_request_no_key` (`request_no`),
  UNIQUE INDEX `service_requests_tenant_id_requester_id_client_key_key` (`tenant_id`, `requester_id`, `client_key`),
  INDEX `service_requests_tenant_id_status_created_at_idx` (`tenant_id`, `status`, `created_at`),
  INDEX `service_requests_tenant_id_customer_id_requester_id_idx` (`tenant_id`, `customer_id`, `requester_id`),
  CONSTRAINT `service_requests_tenant_id_fkey` FOREIGN KEY (`tenant_id`) REFERENCES `tenants` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `service_requests_customer_id_fkey` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `service_requests_requester_id_fkey` FOREIGN KEY (`requester_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `service_requests_processor_id_fkey` FOREIGN KEY (`processor_id`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `service_requests_order_id_fkey` FOREIGN KEY (`order_id`) REFERENCES `orders` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
