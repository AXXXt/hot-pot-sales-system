// 生成独立调试项目，默认连接线上；仅显式指定参数时使用本地后端。
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const destination = path.join(root, '.wx-local-project')
const folders = ['assets', 'components', 'constants', 'pages', 'services', 'store', 'styles', 'utils']
const files = ['app.js', 'app.json', 'app.wxss', 'sitemap.json']
const marker = path.join(destination, '.generated-local-project')

function localMiniConfig({ localBackend = false } = {}) {
  if (!localBackend) return fs.readFileSync(path.join(root, 'config.js'), 'utf8')
  return `// Generated local simulator configuration. Trial/release always use production.
const env = { baseUrl: 'https://weiduoxian.cn', isDevelopment: false }
try {
  const account = wx.getAccountInfoSync()
  const device = wx.getDeviceInfo ? wx.getDeviceInfo() : wx.getSystemInfoSync()
  if (account.miniProgram.envVersion === 'develop' && device.platform === 'devtools') {
    env.baseUrl = 'http://127.0.0.1:3000'
    env.isDevelopment = true
  }
} catch (_) {}
module.exports = env
`
}

function prepare({ localBackend = false } = {}) {
  require('./sync-legal.cjs').syncLegal()
  if (fs.existsSync(destination) && !fs.existsSync(marker)) throw new Error('Refusing to replace an unmanaged directory')
  fs.mkdirSync(destination, { recursive: true })
  fs.writeFileSync(marker, 'Generated by scripts/prepare-local-mini.cjs\n')
  // Refresh only generated runtime trees, so removed source files cannot linger.
  for (const folder of folders) {
    const target = path.join(destination, folder)
    if (path.dirname(target) !== destination) throw new Error('Unsafe generated path')
    fs.rmSync(target, { recursive: true, force: true })
    fs.cpSync(path.join(root, folder), target, { recursive: true, dereference: false })
  }
  for (const file of files) fs.copyFileSync(path.join(root, file), path.join(destination, file))
  fs.writeFileSync(path.join(destination, 'config.js'), localMiniConfig({ localBackend }))
  const project = JSON.parse(fs.readFileSync(path.join(root, 'project.config.json')))
  project.projectname = localBackend ? 'weiduoxian-local-development' : 'weiduoxian-online-development'
  project.setting.urlCheck = false
  project.packOptions.ignore.push({ type: 'file', value: '.generated-local-project' })
  fs.writeFileSync(path.join(destination, 'project.config.json'), JSON.stringify(project, null, 2))
  console.log(`Local mini project: ${destination}`)
  console.log(`Backend: ${localBackend ? 'localhost (simulator only)' : 'https://weiduoxian.cn'}`)
  console.log('Simulator only. Do not upload this generated project; upload the original project for experience builds.')
}

if (require.main === module) prepare({ localBackend: process.argv.includes('--local-backend') })
module.exports = { localMiniConfig }
