// Exercise real transactions and private storage using an isolated temporary local tenant.
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { localConfig } = require('./local-environment.cjs')
const env = localConfig()
process.env.TS_NODE_PROJECT = path.resolve(__dirname, '../backend/tsconfig.json')
process.env.TS_NODE_TRANSPILE_ONLY = '1'
require('../backend/node_modules/ts-node/register')
require('../backend/node_modules/reflect-metadata')
const { PrismaClient } = require('../backend/node_modules/@prisma/client')
const { ConfigService } = require('../backend/node_modules/@nestjs/config')
const { Client } = require('../backend/node_modules/minio')
const sharp = require('../backend/node_modules/sharp')
const { StaffAccessService } = require('../backend/src/auth/staff-access.service')
const { ProductService } = require('../backend/src/product/product.service')
const { AiDraftService } = require('../backend/src/ai/ai-draft.service')
const { AiSettingsService } = require('../backend/src/ai/ai-settings.service')
const { AiAttachmentService } = require('../backend/src/ai/ai-attachment.service')
const { ProductImageStorageService } = require('../backend/src/upload/product-image-storage.service')
const { AiDataService } = require('../backend/src/ai/ai-data.service')
const prisma = new PrismaClient({ datasources: { db: { url: env.DATABASE_URL } } })
let tenantId
const files = []
const storage = new ProductImageStorageService(new Client({ endPoint: '127.0.0.1', port: 9000, useSSL: false, accessKey: env.MINIO_ACCESS_KEY, secretKey: env.MINIO_SECRET_KEY }), new ConfigService(env), prisma)

async function main() {
  const suffix = randomUUID().slice(0, 8)
  const tenant = await prisma.tenant.create({ data: { code: `ai-check-${suffix}`, name: 'AI隔离验证租户' } })
  tenantId = tenant.id
  const user = await prisma.user.create({ data: { tenantId, phone: `test-${suffix}`, name: 'AI隔离验证人员', userType: 'sales' } })
  const other = await prisma.user.create({ data: { tenantId, phone: `other-${suffix}`, name: '附件访问验证', userType: 'sales' } })
  const role = await prisma.role.create({ data: { tenantId, code: 'ai-verification', name: '隔离验证角色' } })
  const codes = ['ai:use', 'ai:execute', 'product:create', 'product:read', 'order:read', 'analytics:view', 'task:manage_own', 'dashboard:view', 'inventory:read']
  const permissions = await prisma.permission.findMany({ where: { code: { in: codes }, status: 'active' } })
  assert.equal(permissions.length, codes.length, 'Required migration permissions must exist')
  await prisma.rolePermission.createMany({ data: permissions.map(p => ({ tenantId, roleId: role.id, permissionId: p.id })) })
  await prisma.userRole.createMany({ data: [user, other].map(x => ({ tenantId, userId: x.id, roleId: role.id })) })
  const brand = await prisma.brand.create({ data: { tenantId, code: 'AITEST', name: 'AI验证品牌' } })
  const inaccessible = await prisma.brand.create({ data: { tenantId, code: 'OTHER', name: '不可见品牌' } })
  await prisma.userBrandAccess.create({ data: { tenantId, userId: user.id, brandId: brand.id } })
  const category = await prisma.productCategory.create({ data: { tenantId, code: 'ai-test', name: '验证涮品' } })
  const access = new StaffAccessService(prisma)
  const settings = new AiSettingsService(prisma, new ConfigService(env), access)
  const products = new ProductService(prisma, {}, {}, {})
  const service = new AiDraftService(prisma, access, products, settings)
  const actor = await access.actor(user.id)
  await prisma.aiConfig.create({ data: { tenantId, enabled: true, allowWrites: true, features: { products: true, tasks: true, analytics: true, vision: true } } })
  const conversation = await prisma.aiConversation.create({ data: { tenantId, ownerId: user.id, title: '隔离验证', fingerprint: actor.fingerprint } })
  const payload = { brandId: brand.id, categoryId: category.id, subtitle: `并发验证-${suffix}`, skus: [{ specText: '500g×20袋', saleUnit: '箱', basePrice: '298.00', minOrderQty: 2 }, { specText: '250g×20袋', saleUnit: '箱', basePrice: '168.00', minOrderQty: 1 }] }
  const draft = await service.create(actor, conversation.id, 'product.create', payload)
  const [first, second] = await Promise.all([service.confirm(actor, draft.id, draft.version, draft.digest), service.confirm(actor, draft.id, draft.version, draft.digest)])
  assert.equal(first.id, second.id, 'Concurrent confirmations must return one execution')
  const created = await prisma.product.findFirst({ where: { tenantId, subtitle: payload.subtitle }, include: { skus: true } })
  assert.equal(created.status, 'disabled'); assert.equal(created.skus.length, 2); assert.ok(created.skus.every(x => x.stockNum === 0))
  assert.equal(await prisma.product.count({ where: { tenantId, subtitle: payload.subtitle } }), 1)
  assert.equal(await prisma.auditLog.count({ where: { tenantId, requestId: `ai-${first.id}` } }), 1)
  console.log('REAL_DB: concurrent confirmation, zero stock, disabled product, atomic audit: OK')

  const rollbackTitle = `回滚验证-${suffix}`
  const rollbackDraft = await service.create(actor, conversation.id, 'product.create', { ...payload, subtitle: rollbackTitle })
  const wrapper = new Proxy(prisma, { get(target, key) {
    if (key === '$transaction') return (callback, options) => prisma.$transaction(tx => callback(new Proxy(tx, { get(real, field) { if (field === 'auditLog') return { create: async () => { throw new Error('INTENTIONAL_AUDIT_FAILURE') } }; return real[field] } })), options)
    return target[key]
  } })
  await assert.rejects(() => new AiDraftService(wrapper, access, products, settings).confirm(actor, rollbackDraft.id, rollbackDraft.version, rollbackDraft.digest), /INTENTIONAL_AUDIT_FAILURE/)
  assert.equal(await prisma.product.count({ where: { tenantId, subtitle: rollbackTitle } }), 0)
  assert.equal(await prisma.aiActionExecution.count({ where: { tenantId, draftId: rollbackDraft.id } }), 0)
  console.log('REAL_DB: failure after business insert rolls back product, SKUs and execution: OK')

  const hiddenDraft = await service.create(actor, conversation.id, 'product.create', { ...payload, brandId: inaccessible.id, subtitle: '不能创建' })
  await assert.rejects(() => service.confirm(actor, hiddenDraft.id, hiddenDraft.version, hiddenDraft.digest), /品牌/)
  const attachmentService = new AiAttachmentService(prisma, access, storage)
  const buffer = await sharp({ create: { width: 8, height: 8, channels: 3, background: '#ffffff' } }).withMetadata({ orientation: 6 }).jpeg().toBuffer()
  const attachment = await attachmentService.upload(actor, { buffer, size: buffer.length, mimetype: 'image/jpeg' })
  const metadata = await prisma.aiAttachment.findUnique({ where: { id: attachment.id } })
  files.push(metadata.objectKey)
  const anonymous = await fetch(`http://127.0.0.1:9000/${env.MINIO_BUCKET}-ai-private/${metadata.objectKey}`)
  assert.equal(anonymous.status, 403)
  const sanitized = await attachmentService.bytes(actor, attachment.id)
  assert.equal((await sharp(sanitized).metadata()).exif, undefined)
  await assert.rejects(() => attachmentService.bytes({ ...actor, id: other.id }, attachment.id), /不可访问/)
  console.log('REAL_STORAGE: anonymous read denied, owner enforced, metadata stripped: OK')

  const data = new AiDataService(prisma, access)
  const metrics = await data.metrics(actor, 'week')
  assert.equal(metrics.amount, '0.00')
  if (process.argv.includes('--http')) {
    const { JwtService } = require('../backend/node_modules/@nestjs/jwt')
    const jwt = new JwtService()
    const headersFor = person => ({ Authorization: `Bearer ${jwt.sign({ sub: person.id, tenantId }, { secret: env.JWT_ACCESS_SECRET, expiresIn: '5m' })}`, 'Content-Type': 'application/json' })
    const headers = headersFor(user)
    const base = 'http://127.0.0.1:3000/api/v1/admin/ai'
    const capabilities = await fetch(`${base}/capabilities`, { headers })
    assert.equal(capabilities.status, 200)
    assert.equal((await capabilities.json()).data.enabled, true)
    assert.equal((await fetch(`${base}/settings`, { headers })).status, 403)
    assert.equal((await fetch(`${base}/conversations/${conversation.id}`, { headers: headersFor(other) })).status, 404)
    assert.equal((await fetch(`${base}/attachments/${attachment.id}`, { headers: headersFor(other) })).status, 404)
    assert.equal((await fetch(`${base}/attachments/${attachment.id}`, { headers })).status, 200)
    const dashboard = await fetch('http://127.0.0.1:3000/api/v1/dashboard/stats', { headers })
    const dashboardBody = await dashboard.json()
    assert.equal(dashboard.status, 200, `Scoped dashboard failed: ${JSON.stringify(dashboardBody)}`)
    assert.equal(dashboardBody.data.todayOrders, 0)
    const invalid = await fetch(`${base}/conversations/${conversation.id}/runs`, { method: 'POST', headers, body: JSON.stringify({ text: '测试', kind: 'metrics', tenantId: 999 }) })
    assert.equal(invalid.status, 400)
    const report = await fetch(`${base}/conversations/${conversation.id}/runs`, { method: 'POST', headers, body: JSON.stringify({ text: '本周经营统计', kind: 'metrics', period: 'week' }) })
    assert.equal(report.status, 201)
    const events = await report.text()
    assert.ok(events.includes('event: result') && events.includes('"amount":"0.00"'))
    assert.ok(!events.includes('event: error'))
    const repeated = await fetch(`${base}/drafts/${draft.id}/confirm`, { method: 'POST', headers, body: JSON.stringify({ version: draft.version, digest: draft.digest }) })
    assert.equal(repeated.status, 201)
    assert.equal((await repeated.json()).data.id, first.id)
    console.log('REAL_HTTP: authentication, explicit permissions, tenant injection rejection, SSE and idempotent confirmation: OK')
  }
  await prisma.userRole.deleteMany({ where: { tenantId, userId: user.id } })
  const revoked = await access.actor(user.id)
  await assert.rejects(() => service.confirm(revoked, rollbackDraft.id, rollbackDraft.version, rollbackDraft.digest), /权限|草稿/)
  console.log('REAL_DB: out-of-scope brand rejected, statistics scoped, revoked grants invalidate drafts: OK')

  const catalogAdmin = await prisma.user.create({ data: { tenantId, phone: `catroot-${suffix}`, name: '目录并发验证', userType: 'super_admin' } })
  const catalogActor = await access.actor(catalogAdmin.id)
  const catalogConversation = await prisma.aiConversation.create({ data: { tenantId, ownerId: catalogActor.id, title: '目录并发验证', fingerprint: catalogActor.fingerprint } })
  const newCatalog = { ...payload, brandId: null, categoryId: null, brandName: `新增品牌${suffix}`, categoryName: `新增分类${suffix}`, subtitle: `组合创建A-${suffix}` }
  const a = await service.create(catalogActor, catalogConversation.id, 'product.create', newCatalog)
  const b = await service.create(catalogActor, catalogConversation.id, 'product.create', { ...newCatalog, subtitle: `组合创建B-${suffix}` })
  const bundles = await Promise.all([service.confirm(catalogActor, a.id, a.version, a.digest), service.confirm(catalogActor, b.id, b.version, b.digest)])
  assert.equal(await prisma.brand.count({ where: { tenantId, name: newCatalog.brandName } }), 1)
  assert.equal(await prisma.productCategory.count({ where: { tenantId, name: newCatalog.categoryName } }), 1)
  assert.equal(bundles.filter(x => x.result.catalog.brand.created).length, 1)
  console.log('REAL_DB: concurrent product bundles reuse one brand and one category: OK')

  const manager = await prisma.user.create({ data: { tenantId, phone: `catmgr-${suffix}`, name: '目录权限验证', userType: 'sales' } })
  const managerRole = await prisma.role.create({ data: { tenantId, code: 'catalog-manager', name: '目录验证角色' } })
  const managerPermissions = await prisma.permission.findMany({ where: { code: { in: ['ai:use', 'ai:execute', 'product:create', 'brand:manage', 'product:update'] } } })
  await prisma.rolePermission.createMany({ data: managerPermissions.map(p => ({ tenantId, roleId: managerRole.id, permissionId: p.id })) })
  await prisma.userRole.create({ data: { tenantId, userId: manager.id, roleId: managerRole.id } })
  const managerActor = await access.actor(manager.id)
  const managerConversation = await prisma.aiConversation.create({ data: { tenantId, ownerId: manager.id, title: '新品牌授权与回滚', fingerprint: managerActor.fingerprint } })
  const failedCatalog = { ...newCatalog, brandName: `回滚品牌${suffix}`, categoryName: `回滚分类${suffix}` }
  const failDraft = await service.create(managerActor, managerConversation.id, 'product.create', failedCatalog)
  const failing = new Proxy(prisma, { get(target, key) {
    if (key === '$transaction') return (callback, options) => prisma.$transaction(tx => callback(new Proxy(tx, { get(real, field) { if (field === 'product') return { ...real.product, create: async () => { throw new Error('INTENTIONAL_PRODUCT_FAILURE') } }; return real[field] } })), options)
    return target[key]
  } })
  await assert.rejects(() => new AiDraftService(failing, access, products, settings).confirm(managerActor, failDraft.id, failDraft.version, failDraft.digest), /INTENTIONAL_PRODUCT_FAILURE/)
  assert.equal(await prisma.brand.count({ where: { tenantId, name: failedCatalog.brandName } }), 0)
  assert.equal(await prisma.productCategory.count({ where: { tenantId, name: failedCatalog.categoryName } }), 0)
  assert.equal(await prisma.userBrandAccess.count({ where: { tenantId, userId: manager.id } }), 0)
  const ownCatalog = await service.confirm(managerActor, failDraft.id, failDraft.version, failDraft.digest)
  const freshManager = await access.actor(manager.id)
  assert.deepEqual(freshManager.brandIds, [ownCatalog.result.catalog.brand.id])
  assert.notEqual(freshManager.fingerprint, managerActor.fingerprint)
  const replay = await service.confirm(freshManager, failDraft.id, failDraft.version, failDraft.digest)
  assert.equal(replay.id, ownCatalog.id)
  console.log('REAL_DB: product failure rolls back new master data and scope; creator gets only its new brand; replay survives authorized scope addition: OK')
}

async function cleanup() {
  for (const key of files) await storage.removeAiImage(key)
  if (!tenantId) return
  for (const name of ['aiActionExecution', 'aiActionDraft', 'aiMessage', 'aiConversation', 'aiAttachment', 'aiUsageRecord', 'aiSchedule', 'opsTask', 'aiConfig', 'auditLog', 'productSku', 'product', 'productCategory', 'userBrandAccess', 'userRole', 'rolePermission', 'role', 'user', 'brand']) await prisma[name].deleteMany({ where: { tenantId } })
  await prisma.tenant.delete({ where: { id: tenantId } })
  console.log('REAL_DB: isolated verification tenant and files removed')
}

main().catch(error => { console.error(`AI_LOCAL_VERIFY_FAILED: ${error.message}`); process.exitCode = 1 }).finally(async () => { try { await cleanup() } finally { await prisma.$disconnect() } })
